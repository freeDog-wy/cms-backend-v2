BEGIN;

CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    -- 原始 Token 的 SHA-256 摘要，固定 32 字节。
    -- 原始 Token 只返回给客户端，不保存到数据库。
    token_hash BYTEA NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_sessions_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT ux_sessions_token_hash
        UNIQUE (token_hash),

    CONSTRAINT ck_sessions_token_hash
        CHECK (octet_length(token_hash) = 32),

    CONSTRAINT ck_sessions_expires_at
        CHECK (expires_at > created_at)
);

-- 查询用户的 Session，以及注销该用户的所有 Session。
CREATE INDEX ix_sessions_user_id
    ON sessions (user_id);

-- 按过期时间清理 Session。
CREATE INDEX ix_sessions_expires_at
    ON sessions (expires_at, id);

COMMENT ON TABLE sessions IS '用户登录会话';
COMMENT ON COLUMN sessions.token_hash IS '随机登录令牌的 SHA-256 摘要';
COMMENT ON COLUMN sessions.expires_at IS '会话的绝对过期时间';

COMMIT;