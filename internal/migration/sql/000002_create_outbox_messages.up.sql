CREATE TABLE outbox_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 根据事件类型选择处理函数。
    event_type VARCHAR(128) NOT NULL,
    payload JSONB NOT NULL,

    -- pending：待执行，包括等待重试
    -- processing：执行中
    -- succeeded：成功
    -- failed：永久失败或次数耗尽
    status VARCHAR(16) NOT NULL DEFAULT 'pending',

    -- 每次成功领取时加一，包含首次执行。
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 10,

    -- pending 状态下，允许被领取的时间。
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 本次领取的令牌和租约到期时间。
    lease_token UUID,
    locked_until TIMESTAMPTZ,

    last_error TEXT,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_outbox_event_type
        CHECK (event_type <> '' AND event_type = btrim(event_type)),

    CONSTRAINT ck_outbox_payload
        CHECK (jsonb_typeof(payload) = 'object'),

    CONSTRAINT ck_outbox_status
        CHECK (status IN (
            'pending', 'processing', 'succeeded', 'failed'
        )),

    CONSTRAINT ck_outbox_attempts
        CHECK (
            max_attempts > 0
            AND attempts >= 0
            AND attempts <= max_attempts
        ),

    CONSTRAINT ck_outbox_lease
        CHECK (
            (status = 'processing'
                AND lease_token IS NOT NULL
                AND locked_until IS NOT NULL)
            OR
            (status <> 'processing'
                AND lease_token IS NULL
                AND locked_until IS NULL)
        ),

    CONSTRAINT ck_outbox_finished
        CHECK (
            (status IN ('succeeded', 'failed')
                AND finished_at IS NOT NULL)
            OR
            (status IN ('pending', 'processing')
                AND finished_at IS NULL)
        )
);

-- 定时扫描到期消息。
CREATE INDEX ix_outbox_ready
    ON outbox_messages (available_at, id)
    WHERE status = 'pending';

-- 回收进程退出、超时等原因遗留的任务。
CREATE INDEX ix_outbox_expired
    ON outbox_messages (locked_until, id)
    WHERE status = 'processing';

-- 按保留时间分批清理成功消息。
CREATE INDEX ix_outbox_cleanup
    ON outbox_messages (finished_at, id)
    WHERE status = 'succeeded';