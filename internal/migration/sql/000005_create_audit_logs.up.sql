CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 执行操作的用户。
    actor_user_id BIGINT NOT NULL,

    -- 资源类型，例如 comment、user、role。
    resource_type VARCHAR(64) NOT NULL,

    -- 资源标识，兼容 BIGINT、UUID 等不同主键。
    resource_id VARCHAR(128) NOT NULL,

    -- 操作标识，例如 comment:moderate、user:disable。
    action VARCHAR(128) NOT NULL,

    -- 修改前后的关键字段，不要求保存完整业务记录。
    before_data JSONB,
    after_data JSONB,

    -- 操作原因。
    reason TEXT NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES users (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_audit_logs_resource_type
        CHECK (resource_type ~ '^[a-z][a-z0-9_]*$'),

    CONSTRAINT ck_audit_logs_resource_id
        CHECK (
            resource_id <> ''
            AND resource_id = btrim(resource_id)
        ),

    CONSTRAINT ck_audit_logs_action
        CHECK (action ~ '^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$'),

    CONSTRAINT ck_audit_logs_before_data
        CHECK (
            before_data IS NULL
            OR jsonb_typeof(before_data) = 'object'
        ),

    CONSTRAINT ck_audit_logs_after_data
        CHECK (
            after_data IS NULL
            OR jsonb_typeof(after_data) = 'object'
        ),

    CONSTRAINT ck_audit_logs_reason
        CHECK (char_length(reason) <= 500)
);

-- 查询某个资源的操作历史。
CREATE INDEX ix_audit_logs_resource
    ON audit_logs (resource_type, resource_id, id);

-- 查询某个用户执行过的操作。
CREATE INDEX ix_audit_logs_actor
    ON audit_logs (actor_user_id, id);

COMMENT ON TABLE audit_logs IS '管理操作审计日志';
COMMENT ON COLUMN audit_logs.resource_id IS '资源主键的字符串表示';
COMMENT ON COLUMN audit_logs.before_data IS '操作前的关键字段';
COMMENT ON COLUMN audit_logs.after_data IS '操作后的关键字段';