BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(64) NOT NULL,
    nickname VARCHAR(64) NOT NULL DEFAULT '',
    email VARCHAR(254),
    password_hash TEXT NOT NULL,

    -- 1：正常，0：禁用
    status SMALLINT NOT NULL DEFAULT 1,

    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_users_username
        CHECK (
            char_length(username) BETWEEN 3 AND 64
            AND username = btrim(username)
        ),

    CONSTRAINT ck_users_email
        CHECK (
            email IS NULL
            OR (email = btrim(email) AND email <> '')
        ),

    CONSTRAINT ck_users_password_hash
        CHECK (password_hash <> ''),

    CONSTRAINT ck_users_status
        CHECK (status IN (0, 1))
);

-- 本例规定用户名不区分大小写：
-- admin 和 Admin 不能注册为两个账号
CREATE UNIQUE INDEX ux_users_username_lower
    ON users (lower(username));

-- 邮箱也按不区分大小写处理；允许多个用户不填邮箱
CREATE UNIQUE INDEX ux_users_email_lower
    ON users (lower(email));

COMMENT ON TABLE users IS '用户表';
COMMENT ON COLUMN users.password_hash IS '密码哈希，禁止保存明文';
COMMENT ON COLUMN users.status IS '账号状态：0禁用，1正常';

COMMIT;