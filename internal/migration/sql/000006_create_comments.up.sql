BEGIN;

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 静态站文章的 commentId，不使用文章路径。
    article_key UUID NOT NULL,

    -- NULL 表示顶层评论，否则表示回复的顶层评论。
    parent_id BIGINT,

    -- 匿名评论填写 guest_name；管理员评论填写 user_id。
    user_id BIGINT,
    guest_name TEXT,

    content TEXT NOT NULL,

    -- pending：待审核，approved：已通过，rejected：已拒绝。
    status VARCHAR(16) NOT NULL DEFAULT 'pending',

    -- 用于审核、删除时的并发控制。
    version BIGINT NOT NULL DEFAULT 1,

    -- 客户端生成的提交标识，用于处理重复提交。
    request_id UUID,

    -- 最近一次审核的信息；完整历史保存在日志表。
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    moderation_reason TEXT NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_comments_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES users (id)
        ON DELETE RESTRICT,

    CONSTRAINT ux_comments_request_id
        UNIQUE (request_id),

    -- 为下面的复合外键提供被引用的唯一键。
    CONSTRAINT ux_comments_id_article_key
        UNIQUE (id, article_key),

    -- 保证父评论存在，并且属于同一篇文章。
    CONSTRAINT fk_comments_parent
        FOREIGN KEY (parent_id, article_key)
        REFERENCES comments (id, article_key)
        ON DELETE RESTRICT,

    CONSTRAINT ck_comments_parent
        CHECK (parent_id IS NULL OR parent_id <> id),

    CONSTRAINT ck_comments_author
        CHECK (
            (
                user_id IS NULL
                AND guest_name IS NOT NULL
                AND char_length(guest_name) BETWEEN 1 AND 40
                AND guest_name = btrim(guest_name)
                AND request_id IS NOT NULL
            )
            OR
            (
                user_id IS NOT NULL
                AND guest_name IS NULL
            )
        ),

    CONSTRAINT ck_comments_content
        CHECK (
            char_length(content) BETWEEN 1 AND 2000
            AND btrim(content) <> ''
        ),

    CONSTRAINT ck_comments_status
        CHECK (status IN ('pending', 'approved', 'rejected')),

    CONSTRAINT ck_comments_version
        CHECK (version > 0),

    CONSTRAINT ck_comments_review
        CHECK (
            (reviewed_by IS NULL) = (reviewed_at IS NULL)
        ),

    CONSTRAINT ck_comments_moderation_reason
        CHECK (char_length(moderation_reason) <= 500)
);

-- 公开的顶层评论列表。
-- 保留已软删除的记录，用于展示“该评论已删除”的占位。
CREATE INDEX ix_comments_public_roots
    ON comments (article_key, id)
    WHERE parent_id IS NULL AND status = 'approved';

-- 公开回复列表，以及计算可见回复数量。
CREATE INDEX ix_comments_public_replies
    ON comments (article_key, parent_id, id)
    WHERE parent_id IS NOT NULL
      AND status = 'approved'
      AND deleted_at IS NULL;

-- 管理后台按状态分页查询。
CREATE INDEX ix_comments_moderation
    ON comments (status, id)
    WHERE deleted_at IS NULL;

-- 查询全部子评论，也支持父评论外键检查。
CREATE INDEX ix_comments_parent_id
    ON comments (parent_id)
    WHERE parent_id IS NOT NULL;

COMMENT ON TABLE comments IS '文章评论';
COMMENT ON COLUMN comments.article_key IS '静态站文章的稳定 UUID';
COMMENT ON COLUMN comments.request_id IS '提交幂等标识';
COMMENT ON COLUMN comments.version IS '评论的并发控制版本号';

COMMIT;