BEGIN;

-- 角色
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 稳定的业务标识，例如 admin、editor
    code VARCHAR(64) NOT NULL,
    name VARCHAR(64) NOT NULL,
    description TEXT NOT NULL DEFAULT '',

    -- 1：启用，0：禁用
    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ux_roles_code UNIQUE (code),
    CONSTRAINT ck_roles_code
        CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT ck_roles_name
        CHECK (name <> '' AND name = btrim(name)),
    CONSTRAINT ck_roles_status
        CHECK (status IN (0, 1))
);

-- 权限
CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 业务权限标识，例如 user:read、article:publish
    code VARCHAR(128) NOT NULL,
    name VARCHAR(64) NOT NULL,
    description TEXT NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ux_permissions_code UNIQUE (code),
    CONSTRAINT ck_permissions_code
        CHECK (code ~ '^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$'),
    CONSTRAINT ck_permissions_name
        CHECK (name <> '' AND name = btrim(name))
);

-- 用户与角色的关联
CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 同一用户不能重复绑定同一角色
    PRIMARY KEY (user_id, role_id),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES roles (id)
        ON DELETE CASCADE
);

-- 主键已经支持按 user_id 查询；
-- 补充反向查询及角色删除时需要的索引。
CREATE INDEX ix_user_roles_role_id
    ON user_roles (role_id, user_id);

-- 角色与权限的关联
CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (role_id, permission_id),

    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_id)
        REFERENCES roles (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (permission_id)
        REFERENCES permissions (id)
        ON DELETE CASCADE
);

CREATE INDEX ix_role_permissions_permission_id
    ON role_permissions (permission_id, role_id);

COMMENT ON TABLE roles IS '角色表';
COMMENT ON TABLE permissions IS '业务权限表';
COMMENT ON TABLE user_roles IS '用户角色关联表';
COMMENT ON TABLE role_permissions IS '角色权限关联表';

COMMIT;